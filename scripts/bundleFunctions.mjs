/**
 * Bundles the production API routes into self-contained files in `api/`.
 *
 * WHY THIS EXISTS. Vercel transpiles each file in `api/` on its own and does
 * not rewrite import specifiers. This repo imports with explicit `.ts`
 * extensions — `allowImportingTsExtensions`, which TypeScript only permits
 * alongside `noEmit` — so a transpiled `api/critique.js` kept asking Node for
 * `../plugins/routes.ts` at runtime and died with ERR_MODULE_NOT_FOUND. Writing
 * `.js` specifiers instead would fix the emitted import but would mean changing
 * how `src/` imports itself, where Vite wants the `.ts` form.
 *
 * So the routes are bundled here instead, ahead of the deploy. Each output is
 * one file with no relative imports at all, which leaves Vercel nothing to
 * resolve and no TypeScript to compile — the one arrangement that cannot
 * depend on another tool's resolution rules.
 *
 * The sources live in `functions/` rather than `api/` so that Vercel sees
 * exactly one candidate entry point per route. The outputs are committed,
 * because function detection reads the deployed file tree and relying on it to
 * notice a file the build had just written would put this back to guessing.
 * `npm run build` regenerates them, so a stale bundle shows up as a git diff
 * rather than as a broken deploy.
 */

import { rolldown } from 'rolldown'
import { readFileSync, writeFileSync } from 'node:fs'

const ROUTES = ['critique', 'blueprint']

const BANNER = `// GENERATED by scripts/bundleFunctions.mjs from functions/%NAME%.ts
// Do not edit. Run \`npm run build\` (or \`npm run build:api\`) to regenerate.
`

for (const name of ROUTES) {
  const bundle = await rolldown({
    input: `functions/${name}.ts`,
    // Node builtins stay external; everything else is inlined.
    platform: 'node',
  })
  const out = `api/${name}.js`
  await bundle.write({ file: out, format: 'esm', codeSplitting: false })
  await bundle.close()

  // Prepended after the fact so the banner survives whatever the bundler does
  // to the top of the file.
  writeFileSync(out, BANNER.replace('%NAME%', name) + readFileSync(out, 'utf8'))
  console.log(`bundled ${out}`)
}
